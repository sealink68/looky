#!/usr/bin/env python3
"""gen_precache.py – writes the service-worker precache list into sw.js.

Run from anywhere after adding/changing app files (images, JS, CSS, ...):
    python3 tools/gen_precache.py          # rewrite the generated block in sw.js
    python3 tools/gen_precache.py --check  # exit 1 if sw.js is out of date (used by the tests)

Every runtime file of the app (HTML, CSS, JS, manifest, icons, logos, product/help images, fonts) is listed.
PRECACHE_HASH is a content hash of all listed files: any change to any asset changes sw.js, so browsers
install the new version (and the app shows the "new version" banner)."""
import hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SW = os.path.join(ROOT, "sw.js")
EXT = {".html", ".css", ".js", ".json", ".webmanifest", ".png", ".jpg", ".jpeg", ".svg", ".ico", ".webp", ".gif",
       ".woff", ".woff2", ".ttf", ".otf"}
SKIP_DIRS = {".git", ".github", "tools", "tests", "node_modules"}
SKIP_FILES = {"sw.js"}
BEGIN, END = "/* PRECACHE:BEGIN", "/* PRECACHE:END */"


def assets():
    out = []
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS and not x.startswith("."))
        for f in sorted(files):
            rel = os.path.relpath(os.path.join(d, f), ROOT).replace(os.sep, "/")
            if rel in SKIP_FILES or f.startswith(".") or os.path.splitext(f)[1].lower() not in EXT:
                continue
            out.append(rel)
    # page itself first (also reachable as "./"), then the rest alphabetically
    out.sort(key=lambda p: (p != "index.html", p))
    return out


def block():
    files = assets()
    h, total = hashlib.sha256(), 0
    for rel in files:
        data = open(os.path.join(ROOT, rel), "rb").read()
        total += len(data)
        h.update(rel.encode() + b"\0" + hashlib.sha256(data).digest())
    total += os.path.getsize(os.path.join(ROOT, "index.html"))  # "./" is the same page, cached a 2nd time
    lines = ['  "./",'] + ['  "%s",' % f for f in files]
    lines[-1] = lines[-1].rstrip(",")
    txt = (BEGIN + " – generated by tools/gen_precache.py, do not edit by hand */\n"
           'var PRECACHE_HASH = "%s";\n' % h.hexdigest()[:12] +
           "var PRECACHE_BYTES = %d;\n" % total +
           "var PRECACHE = [\n" + "\n".join(lines) + "\n];\n" + END)
    return txt, len(files) + 1, total


def main():
    src = open(SW, encoding="utf-8").read()
    i, j = src.find(BEGIN), src.find(END)
    if i < 0 or j < 0:
        sys.exit("sw.js has no PRECACHE:BEGIN / PRECACHE:END markers")
    txt, n, total = block()
    new = src[:i] + txt + src[j + len(END):]
    if "--check" in sys.argv:
        if new != src:
            print("sw.js precache list is OUT OF DATE – run: python3 tools/gen_precache.py"); sys.exit(1)
        print("sw.js precache list up to date: %d entries, %.2f MB" % (n, total / 1048576)); return
    if new != src:
        open(SW, "w", encoding="utf-8", newline="\n").write(new)
    print("sw.js: %d precache entries, %.2f MB, hash %s" % (n, total / 1048576, re.search(r'PRECACHE_HASH = "(\w+)"', txt).group(1)))


if __name__ == "__main__":
    main()
